/**
 * 标签输入的拆分规则。
 *
 * 创建表单与详情页的编辑面板都要把用户的逗号输入拆成数组，之前两处各写了一份
 * 一模一样的实现 —— 拆分规则是「前端能提交什么」的第一道口径，两份实现一旦漂移，
 * 就会出现「两个页面看着一样、提交结果不一样」。
 *
 * ⚠️ 这里**不做**去重与大小写归一：那是后端的职责（存储统一小写、按小写比较），
 *    前端顺手做一份只会多出一处需要同步的规则。
 */

/**
 * 把逗号分隔的输入拆成标签数组。
 *
 * 半角 `,` 与全角 `，` 都认（中文输入法下很容易打出全角）；
 * 逐项 trim 并丢掉空项，于是 `"ops, , dev"` → `["ops", "dev"]`。
 */
export function splitTags(raw: string): string[] {
  return raw
    .split(/[,，]/)
    .map((item) => item.trim())
    .filter((item) => item.length > 0)
}
